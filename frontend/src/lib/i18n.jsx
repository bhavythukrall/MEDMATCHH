const DICT = { en, hi };

const LangContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem(STORE_KEY) || "en");
  useEffect(() => {
    localStorage.setItem(STORE_KEY, lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  const toggle = () => setLang((l) => (l === "en" ? "hi" : "en"));
  const specialty = (s) => t(`spec.${String(s || "general").toLowerCase()}`);
  const status = (s) => t(`status.${String(s || "").toLowerCase()}`);

  return (
    <LangContext.Provider value={{ lang, setLang, toggle, t, specialty, status }}>
      {children}
    </LangContext.Provider>
  );
}

export const useT = () => useContext(LangContext);
